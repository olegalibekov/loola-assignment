def _pytest(workspace: Path, *targets: str) -> bool:
    env = {**os.environ, "PYTHONPATH": str(workspace), "PYTHONDONTWRITEBYTECODE": "1"}
    try:
        proc = subprocess.run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", *targets],
                              cwd=workspace, env=env, capture_output=True, text=True, timeout=180)
    except subprocess.TimeoutExpired:
        return False
    return proc.returncode == 0


def _git(workspace: Path, *args: str) -> str:
    return subprocess.run(["git", *args], cwd=workspace, capture_output=True, text=True).stdout


def _read(workspace: Path, rel: str) -> str:
    try:
        return (workspace / rel).read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return ""


def _line(text: str, label: str) -> str | None:
    match = re.search(rf"^[\s\-*]*{label}\**\s*:\**\s*(.+?)\s*$", text, re.M | re.I)  # tolerate "- **Label:** x"
    return match.group(1).strip("`* ") if match else None


# --------------------------------------------------------------------------- checks


def check(workspace: Path, seed: int = DEFAULT_SEED) -> dict:
    workspace = Path(workspace).resolve()
    ref = reference(seed)
    checks: dict[str, bool] = {}

    # git first: running tests below must not be able to dirty the tree
    tracked = set(_git(workspace, "ls-files").split())
    dirty = [line for line in _git(workspace, "status", "--porcelain").splitlines() if not line.startswith("??")]
    required = {"notes/incident.txt", "out/summary.json", "REPORT.md", "CHANGELOG.md", "tests/test_top_products.py"}
    checks["git_commit"] = (
        _git(workspace, "log", "-1", "--format=%s").startswith("fix:")
        and int(_git(workspace, "rev-list", "--count", "HEAD").strip() or 0) >= 2
        and not dirty and required <= tracked
        and not any("__pycache__" in path or ".pytest_cache" in path for path in tracked))

    note = _read(workspace, "notes/incident.txt")
    checks["incident_note"] = (re.search(r"^incident=(\S+)\s*$", note, re.M) is not None
                               and re.search(r"^incident=(\S+)\s*$", note, re.M).group(1) == ref["incident"]
                               and re.search(rf"^sku={re.escape(ref['incident_sku'])}\s*$", note, re.M) is not None)

    checks["tests_pass"] = (workspace / "tests").is_dir() and _pytest(workspace, "tests")
    with tempfile.TemporaryDirectory() as tmp:
        for name, body in HIDDEN.items():
            path = Path(tmp) / f"test_{name}.py"
            path.write_text(_PRELUDE + body, encoding="utf-8")
            checks[name] = _pytest(workspace, str(path))

    try:
        checks["summary_json"] = json.loads(_read(workspace, "out/summary.json")) == ref["summary"]
    except json.JSONDecodeError:
        checks["summary_json"] = False

    new_tests = _read(workspace, "tests/test_top_products.py")
    checks["new_tests"] = (len(re.findall(r"^def test_\w+", new_tests, re.M)) >= 3 and "top_products" in new_tests
                           and _pytest(workspace, "tests/test_top_products.py"))

    changelog = _read(workspace, "CHANGELOG.md")
    unreleased = changelog.split("## [Unreleased]", 1)[-1].split("## [0.1.0]", 1)[0] if "## [Unreleased]" in changelog else ""
    fixed = unreleased.split("### Fixed", 1)[-1].split("###", 1)[0] if "### Fixed" in unreleased else ""
    added = unreleased.split("### Added", 1)[-1].split("###", 1)[0] if "### Added" in unreleased else ""
    checks["changelog"] = (all(word in fixed for word in ("parser", "pricing", "stock"))
                           and len(re.findall(r"^\s*[-*] ", fixed, re.M)) >= 3
                           and "top_products" in added and "summary" in added
                           and "regions` command printing revenue per region" in changelog)

    report = _read(workspace, "REPORT.md")
    checks["report"] = (_line(report, "Incident") == ref["incident"]
                        and _line(report, "Total revenue") == ref["summary"]["total_revenue"]
                        and _line(report, "Top SKU") == ref["summary"]["top_sku"]
                        and _line(report, "Incident SKU stock") == str(ref["incident_sku_stock"]))

    passed = sum(checks.values())
    return {"success": passed == len(checks), "passed": passed, "total": len(checks), "checks": checks}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("workspace", type=Path)
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    args = parser.parse_args()
    result = check(args.workspace, args.seed)
    print(json.dumps(result, indent=2))
    raise SystemExit(0 if result["success"] else 1)
