"""Deterministic checker for the benchmark task: 12 independent checks, success = all pass.

Expected values are recomputed here from pristine data regenerated by seed - never taken from
the agent's code or files. Hidden tests run against the agent's `inventory` package, so editing
the visible tests does not help.

    python -m bench.task.check path/to/workspace [--seed 7]
"""
