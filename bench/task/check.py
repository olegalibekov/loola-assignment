# --------------------------------------------------------------------------- reference answers


def reference(seed: int = DEFAULT_SEED) -> dict:
    """Independent implementation of the spec over pristine data."""
    data = build_data(seed)
    fatal = next(line for line in data["logs/app.log"].splitlines() if " FATAL " in line)
    incident = re.search(r"incident=(\S+)", fatal).group(1)
    incident_sku = re.search(r"sku=(\S+)", fatal).group(1)

    by_region: dict[str, Decimal] = defaultdict(Decimal)
    by_sku: dict[str, Decimal] = defaultdict(Decimal)
    shipped: dict[str, int] = defaultdict(int)
    completed = 0
    for row in csv.DictReader(io.StringIO(data["data/orders.csv"])):
        if row["status"].strip().lower() != "completed":
            continue
        completed += 1
        sku, region = row["sku"].strip().upper(), row["region"].strip().upper()
        quantity, discount = int(row["quantity"]), int(row["discount_pct"].strip() or 0)
        total = (Decimal(row["unit_price"].strip()) * quantity * (100 - discount) / 100).quantize(
            Decimal("0.01"), rounding=ROUND_HALF_UP)
        by_region[region] += total
        by_sku[sku] += total
        shipped[sku] += quantity
    initial = {p["sku"]: p["initial_stock"] for p in json.loads(data["data/products.json"])}
    top_sku = sorted(by_sku.items(), key=lambda item: (-item[1], item[0]))[0][0]
    return {
        "incident": incident,
        "incident_sku": incident_sku,
        "incident_sku_stock": initial[incident_sku] - shipped[incident_sku],
        "summary": {"orders": completed, "total_revenue": f"{sum(by_region.values()):.2f}", "top_sku": top_sku,
                    "revenue_by_region": {region: f"{value:.2f}" for region, value in sorted(by_region.items())}},
    }


